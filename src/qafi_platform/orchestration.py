"""Laptop-side helpers for notebook 06: run the local Airflow and follow a DAG run.

Airflow runs through ``airflow/airflow.sh``, which applies this project's settings. ``start_airflow``
starts the scheduler and the web UI in the background and returns once the UI answers;
``airflow_password`` reads the login Airflow generated; ``start_dag_run`` switches a DAG on and makes
sure one run starts; ``wait_for_dag_run`` waits for that run and lists its tasks; ``stop_airflow``
shuts everything down again.

Runs and tasks are read through Airflow's REST API, which answers in JSON. The command line is not
used for this, because its output mixes the answer with Airflow's own log lines.
"""

from __future__ import annotations

import json
import os
import signal
import subprocess
import time
import urllib.request
from pathlib import Path
from urllib.parse import quote

import pandas as pd

UI = "http://localhost:8080"


def _api(root: Path, method: str, path: str, body: dict | None = None) -> dict:
    """Call Airflow's REST API (``/api/v2`` + ``path``) as the user ``admin``."""
    login = urllib.request.Request(
        f"{UI}/auth/token",
        data=json.dumps({"username": "admin", "password": airflow_password(root)}).encode(),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(login, timeout=30) as response:
        token = json.load(response)["access_token"]
    request = urllib.request.Request(
        f"{UI}/api/v2{path}",
        data=None if body is None else json.dumps(body).encode(),
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        method=method,
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def _runs(root: Path, dag_id: str) -> list[dict]:
    """The DAG's runs, newest first."""
    return _api(root, "GET", f"/dags/{dag_id}/dagRuns?order_by=-run_after&limit=100")["dag_runs"]


def start_airflow(root: Path, timeout: int = 300) -> subprocess.Popen:
    """Start ``airflow standalone`` in the background and wait until its scheduler and web UI are up."""
    home = root / "airflow" / ".airflow"
    home.mkdir(parents=True, exist_ok=True)
    log = open(home / "standalone.log", "w")  # stays open: Airflow writes to it while it runs
    process = subprocess.Popen(
        [str(root / "airflow" / "airflow.sh"), "standalone"],
        stdout=log,
        stderr=subprocess.STDOUT,
        start_new_session=True,  # its own process group, so stop_airflow can stop all of its parts
    )
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise RuntimeError(f"Airflow stopped while starting; see {home / 'standalone.log'}")
        try:
            with urllib.request.urlopen(f"{UI}/api/v2/monitor/health", timeout=5) as response:
                if json.load(response)["scheduler"]["status"] == "healthy":
                    return process
        except (OSError, ValueError, KeyError):  # not answering yet
            pass
        time.sleep(3)
    stop_airflow(process)
    raise TimeoutError(f"Airflow not up after {timeout} s; see {home / 'standalone.log'}")


def airflow_password(root: Path) -> str:
    """The password of the user ``admin``, generated by Airflow on its first start."""
    path = root / "airflow" / ".airflow" / "simple_auth_manager_passwords.json.generated"
    return json.loads(path.read_text())["admin"]


def start_dag_run(root: Path, dag_id: str, wait: int = 30) -> str:
    """Switch the DAG on and make sure exactly one run is going; returns its run ID.

    A run already queued or running (say, started with the Trigger button) is the one returned.
    Otherwise, switching a DAG on starts the scheduled run it has missed, if its last scheduled
    time has passed; if it has not, this starts a run by hand, as the Trigger button does.
    """
    before = _runs(root, dag_id)
    going = [r["dag_run_id"] for r in before if r["state"] in ("queued", "running")]
    if going:
        return going[0]
    _api(root, "PATCH", f"/dags/{dag_id}", {"is_paused": False})
    deadline = time.monotonic() + wait
    while time.monotonic() < deadline:
        known = {r["dag_run_id"] for r in before}
        new = [r["dag_run_id"] for r in _runs(root, dag_id) if r["dag_run_id"] not in known]
        if new:
            return new[0]
        time.sleep(5)
    return _api(root, "POST", f"/dags/{dag_id}/dagRuns", {"logical_date": None})["dag_run_id"]


def wait_for_dag_run(root: Path, dag_id: str, run_id: str, timeout: int = 1800) -> pd.DataFrame:
    """Wait until the run ``run_id`` of ``dag_id`` has finished; one row per task, in the order they ran."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        run = _api(root, "GET", f"/dags/{dag_id}/dagRuns/{quote(run_id, safe='')}")
        if run["state"] in ("success", "failed"):
            path = f"/dags/{dag_id}/dagRuns/{quote(run_id, safe='')}/taskInstances"
            tasks = _api(root, "GET", path)["task_instances"]
            print(f"{run_id}: {run['state']}")
            columns = ["task_id", "state", "start_date", "end_date"]
            return pd.DataFrame(tasks)[columns].sort_values("start_date", ignore_index=True)
        time.sleep(15)
    raise TimeoutError(f"run {run_id} of {dag_id} not finished after {timeout} s")


def stop_airflow(process: subprocess.Popen) -> None:
    """Stop the scheduler, the web UI and the rest of ``airflow standalone``."""
    if process.poll() is None:
        os.killpg(process.pid, signal.SIGINT)
        try:
            process.wait(timeout=60)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            process.wait()
